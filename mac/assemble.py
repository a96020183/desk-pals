"""Assemble mac/src/*.swift into extension/desktop/DeskPals.swift (single file the launcher compiles).

//@@IN <Class> ... //@@END blocks (top level, any file) are moved into the body of <Class>,
at the line `//@@BODY <Class>` in the owner file.
Usage: python3 mac/assemble.py            → extension/desktop/DeskPals.swift (personal: every lineup)
       python3 mac/assemble.py --public   → build/public/extension/desktop/DeskPals.swift (no fan-art lineups; see tools/variant.py)
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "..", "extension", "desktop", "DeskPals.swift")


def source_files():
    return sorted(glob.glob(os.path.join(ROOT, "src", "*.swift")))


def assemble(files, transform=None):
    bodies = {}      # class -> list of lines
    texts = []
    for f in files:
        text = open(f, encoding="utf-8").read()
        if transform:
            text = transform(text, os.path.relpath(f, os.path.join(ROOT, "..")).replace(os.sep, "/"))
        out, cur = [], None
        for ln in text.split("\n"):
            m = re.match(r"^\s*//@@IN\s+(\w+)\s*$", ln)
            if m and cur is None:
                cur = m.group(1)
                bodies.setdefault(cur, []).append(f"    // ---- from {os.path.basename(f)} ----")
                continue
            if cur is not None:
                if re.match(r"^\s*//@@END\s*$", ln):
                    cur = None
                else:
                    bodies[cur].append(ln)
                continue
            out.append(ln)
        if cur is not None:
            sys.exit(f"{f}: unterminated //@@IN {cur}")
        texts.append((f, out))

    used = set()
    result = ["// GENERATED by mac/assemble.py from mac/src/*.swift — edit those, not this file.",
              "// 公仔櫃 Desk Pals — macOS port of DeskPals.cs"]
    for f, lines in texts:
        result.append(f"// ===== {os.path.basename(f)} =====")
        for ln in lines:
            m = re.match(r"^\s*//@@BODY\s+(\w+)\s*$", ln)
            if m:
                used.add(m.group(1))
                result.extend(bodies.get(m.group(1), []))
            else:
                result.append(ln)
    missing = set(bodies) - used
    if missing:
        print("warning: no //@@BODY marker for: " + ", ".join(sorted(missing)), file=sys.stderr)
    return "\n".join(result) + "\n"


def main(argv):
    if "--public" in argv:
        sys.path.insert(0, os.path.join(ROOT, "..", "tools"))
        import variant  # noqa: E402
        out = os.path.join(ROOT, "..", "build", "public", "extension", "desktop", "DeskPals.swift")
        text = variant.public_swift()
    else:
        out = OUT
        files = source_files()
        text = assemble(files)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w", encoding="utf-8", newline="\n").write(text)   # LF on every OS (CI diffs against the committed file)
    print(f"wrote {os.path.relpath(out)} ({text.count(chr(10))} lines)")


if __name__ == "__main__":
    main(sys.argv[1:])
